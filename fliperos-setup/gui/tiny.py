def width(s):
    return max(0, len(s) * 4 - 1)


def text(surf, s, color, x, y, right=False):
    """Escreve s (em maiusculas) em (x, y); devolve a largura."""
    s = s.upper()
    if right:
        x -= width(s)
    for i, ch in enumerate(s):
        bits = GLYPHS.get(ch, GLYPHS["?"])
        for r in range(5):
            for c in range(3):
                if bits[r * 3 + c] == "1":
                    surf.fill(color, (x + i * 4 + c, y + r, 1, 1))
    return width(s)


def centered(surf, s, color, cx, y):
    text(surf, s, color, cx - width(s) // 2, y)


def fit(s, w):
    """s cortado para caber em w pixels."""
    s = s.upper()
    if width(s) <= w:
        return s
    while s and width(s + "..") > w:
        s = s[:-1]
    return s + ".."
