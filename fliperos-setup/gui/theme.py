def guess(title, value, label):
    """O icone de um item sem icone com o nome dele, pelo que ele parece ser:
    uma pasta ou um arquivo do seletor de pastas, um disco, ou o assunto do
    menu (redes, monitores, placas de som). "" = nenhum."""
    title = title.lower()
    if value.startswith("/dev/") or "disk" in title:
        return "disk"
    if label.endswith("/") or label == "..":
        return "up" if label == ".." else "dest"
    if value.isdigit() and value not in label:
        return "romlist"        # um arquivo, pelo numero dele na lista
    for word, name in (("wi-fi", "network"), ("network", "network"), ("monitor", "video"), ("output", "outputs"),
                       ("card", "audio"), ("audio", "audio"), ("folder", "dest"), ("usb", "usb"),
                       ("quirk", "quirks"), ("torrent", "install"), ("frontend", "frontend"),
                       ("emulator", "emulators"), ("update", "reset"), ("gun", "guncon"),
                       ("wheel", "axes"), ("controller", "joysticks"), ("joystick", "joysticks")):
        if word in title:
            return name
    return ""


def icon(name, scale):
    """A surface do icone, que cabe em 16*scale pixels, ou None quando nao
    ha icone com o nome: um desenho de ICONS ou uma imagem de gui/icons."""
    if (name, scale) in _icons:
        return _icons[(name, scale)]
    size = 16 * scale
    img = None
    path = os.path.join(ICON_DIR, IMAGES.get(name, name) + ".png")
    if name in ICONS:
        surf = pygame.Surface((16, 16), pygame.SRCALPHA)
        for y, row in enumerate(ICONS[name].split()):
            for x, ch in enumerate(row):
                if ch != ".":
                    surf.set_at((x, y), ICON_COLORS[ch])
        img = pygame.transform.scale(surf, (size, size))
    elif name.replace("-", "").replace("_", "").isalnum() and os.path.isfile(path):
        try:
            src = pygame.image.load(path)
            k = size / max(src.get_size())
            img = pygame.transform.smoothscale(src, (max(1, round(src.get_width() * k)),
                                                     max(1, round(src.get_height() * k))))
        except pygame.error:
            img = None
    _icons[(name, scale)] = img
    return img


