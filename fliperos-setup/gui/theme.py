_font = None


def font():
    global _font
    if _font is None:
        if not os.path.isfile(FONT_FILE):
            raise SystemExit("fliperos-gui: font not found: " + FONT_FILE)
        _font = pygame.font.Font(FONT_FILE, 8)
    return _font


