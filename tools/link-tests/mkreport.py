import sys, re, collections, xml.etree.ElementTree as ET
SRC = "/src"
real_s32_inits = {"init_f1lap":"15612","init_f1lapt":"15612","init_orunners":"15033","init_radr":"14084","init_scross":"15033"}
s32games = {}
for line in open(SRC+"/segas32.cpp", encoding="utf8", errors="ignore"):
    m = re.match(r"\s*GAMEL?\(\s*[\d?]+,\s*(\w+),\s*(\w+),\s*(\w+),\s*(\w+),\s*(\w+),\s*(init_\w+)", line)
    if m and m.group(6) in real_s32_inits:
        s32games[m.group(1)] = real_s32_inits[m.group(6)]
gun = set()
for line in open("/src2/gunbustr.cpp", encoding="utf8", errors="ignore"):
    m = re.match(r"\s*GAMEL?\(\s*\d+,\s*(\w+),", line)
    if m: gun.add(m.group(1))
M = {}
for ev, el in ET.iterparse(sys.stdin.buffer, events=("end",)):
    if el.tag != "machine": continue
    if el.get("isdevice") == "yes" or el.get("isbios") == "yes": el.clear(); continue
    devs = {d.get("name") for d in el.findall("device_ref")}
    feats = [(f.get("type"), f.get("status") or f.get("overall")) for f in el.findall("feature") if f.get("type") in ("lan","wan","comms")]
    M[el.get("name")] = dict(parent=el.get("cloneof") or "", desc=el.findtext("description"), year=el.findtext("year"), manu=el.findtext("manufacturer"),
        src=(el.get("sourcefile") or ""), devs=devs, feats=feats, status=(el.find("driver").get("status") if el.find("driver") is not None else ""))
    el.clear()
def row(n):
    m = M[n]; return f"| `{n}` | {m['parent'] or ''} | {m['desc']} | {m['year']} | {m['manu']} |"
def table(names):
    out = ["| set | clone of | description | year | maker |", "|---|---|---|---|---|"]
    out += [row(n) for n in sorted(names, key=lambda x: (M[x]['parent'] or x, M[x]['parent'] != '', x))]
    return "\n".join(out)
def with_dev(d): return [n for n, m in M.items() if d in m['devs']]
out = []
out.append("# MAME 0.289 games that link to other machines (from the source code and the XML)\n")
out.append("Generated by `tools/link-tests/mkreport.py` from `mame -listxml` (device_ref and features) and from reading src/mame at tag mame0289.\n")
out.append("## A. Boards with a real network link (the code opens TCP sockets and runs a protocol)\n")
out.append("### A1. cps2comm: Capcom CPS-2 (TCP chain, needs Machine Configuration `Communication = Enable`)\n")
out.append(table([n for n in with_dev("cps2comm")]) + "\n\n`ssf2tbd` (bootleg) uses `dead_cps2comm`: the board is there but has no link.\n")
out.append("### A2. gunbustr_link: Taito Gunbuster (a pair; `Link Simulation = Enable` plus the test menu Configuration > Link Play and ID)\n")
out.append(table([n for n in M if n in gun]) + "\n")
out.append("### A3. m1comm: Sega Model 1 (TCP ring; the role is set by the game)\n")
out.append(table(with_dev("m1comm")) + "\n")
out.append("### A4. s32comm: Sega System 32 (TCP ring). The board is in every System 32 game, but only these call `set_linktype`:\n")
out.append(table([n for n in s32games if n in M]) + "\n")
out.append("### A5. m2comm: Sega Model 2 (TCP ring; the role is set in the test menu). The board is in EVERY Model 2 game; which ones really use the link depends on the game (LINK and NETWORK items in the test menu):\n")
out.append(table(with_dev("m2comm")) + "\n")
out.append("## B. Board present but no network emulated (stub)\n")
for dev, label in (("m3comm","m3comm: Sega Model 3 / NAOMI / Hikaru (network code commented out)"),("seganetw","seganetw: Sega Network Board (Chihiro/Triforce; only a ROM)"),
                   ("konami_gn676a_lan","konami_gn676a_lan: Konami GN676-PWB(H)A (memory registers only)"),("konami_gn676b_lan","konami_gn676b_lan: Konami GN676-PWB(H)B (memory registers only)"),
                   ("k056230","k056230: Konami LANC (a wrapper so the POST passes)"),("namco_c139","namco_c139: Namco C139 serial (TODO in the source: make it work)"),
                   ("gaelco_serial","gaelco_serial: Gaelco 3D (link through shared memory only if MAME is rebuilt with SHARED_MEM_DRIVER)")):
    ns = with_dev(dev)
    out.append(f"### {label}: {len(ns)} sets\n")
    parents = sorted({M[n]['parent'] or n for n in ns})
    out.append("Games (parents): " + ", ".join(f"`{p}`" for p in parents[:400]) + "\n")
out.append("## C. Marked by MAME as network or serial link NOT emulated (feature lan/comms/wan)\n")
flag = [n for n, m in M.items() if m['feats']]
par = sorted({M[n]['parent'] or n for n in flag})
out.append(f"{len(flag)} sets ({len(par)} parent games). No MAME code reads `comm_*` for them.\n")
out.append("| parent | description | maker | year | feature |\n|---|---|---|---|---|")
for p in par:
    m = M[p] if p in M else M[[n for n in flag if (M[n]['parent'] or n) == p][0]]
    out.append(f"| `{p}` | {m['desc']} | {m['manu']} | {m['year']} | {','.join(a+':'+str(b) for a,b in m['feats'])} |")
sys.stdout.write("\n".join(out) + "\n")
