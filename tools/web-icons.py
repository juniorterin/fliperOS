def theme_icons():
    """{nome: [linhas]} e {letra: "#rrggbb"} dos icones do theme.py."""
    tree = ast.parse(open(THEME, encoding="utf-8").read())
    consts, letters, icons = {}, {}, {}

    def add(node):
        for k, v in zip(node.keys, node.values):
            if isinstance(k, ast.Constant) and isinstance(v, ast.Constant) and k.value not in icons:
                icons[k.value] = [r for r in v.value.split() if r]

    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            name, value = node.targets[0].id, node.value
            if isinstance(value, ast.Tuple) and len(value.elts) == 3 and all(
                    isinstance(e, ast.Constant) and isinstance(e.value, int) for e in value.elts):
                consts[name] = "#%02x%02x%02x" % tuple(e.value for e in value.elts)
            elif name == "ICON_COLORS":
                letters = {k.value: consts[v.id] for k, v in zip(value.keys, value.values)}
            elif name == "ICONS":
                add(value)
        elif (isinstance(node, ast.Expr) and isinstance(node.value, ast.Call)
              and ast.unparse(node.value.func) == "ICONS.update" and isinstance(node.value.args[0], ast.Dict)):
            add(node.value.args[0])
    return icons, letters


def runs(rows, on):
    """(x, y, largura, letra) de cada trecho seguido da mesma cor."""
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            w = 1
            while x + w < len(row) and row[x + w] == row[x]:
                w += 1
            if on(row[x]):
                yield x, y, w, row[x]
            x += w


def sprite():
    icons, letters = theme_icons()
    out = ['<svg xmlns="http://www.w3.org/2000/svg" style="display:none">',
           "<!-- Gerado por tools/web-icons.py: os icones do Setup (theme.py) e os glifos do painel. -->"]
    for name, rows in icons.items():
        paths = {}
        for x, y, w, c in runs(rows, lambda c: c in letters):
            paths.setdefault(letters[c], []).append("M%d %dh%dv1h-%dz" % (x, y, w, w))
        body = "".join('<path fill="%s" d="%s"/>' % (color, "".join(d)) for color, d in paths.items())
        out.append('<symbol id="px-%s" viewBox="0 0 16 16" shape-rendering="crispEdges">%s</symbol>' % (name, body))
    for name, art in GLYPHS.items():
        rows = [r for r in art.split("\n") if r.strip()]
        assert [len(r) for r in rows] == [12] * 12, name
        d = "".join("M%d %dh%dv1h-%dz" % (x, y, w, w) for x, y, w, _ in runs(rows, lambda c: c == "#"))
        out.append('<symbol id="g-%s" viewBox="0 0 12 12" shape-rendering="crispEdges" fill="currentColor">'
                   '<path d="%s"/></symbol>' % (name, d))
    out.append("</svg>")
    return ("\n".join(out) + "\n").encode()


def png(size, scale):
    """O joystick do Setup em size x size, cada pixel do icone virando
    scale x scale, no fundo escuro do painel."""
    icons, letters = theme_icons()
    rows = icons["frontend"]
    bg = (0x19, 0x1A, 0x21)
    pad = (size - 16 * scale) // 2
    lines = []
    for y in range(size):
        line = bytearray([0])
        iy = (y - pad) // scale
        for x in range(size):
            ix = (x - pad) // scale
            c = rows[iy][ix] if 0 <= iy < 16 and 0 <= ix < 16 and y >= pad and x >= pad else "."
            line += bytes(int(letters[c][i:i + 2], 16) for i in (1, 3, 5)) if c in letters else bytes(bg)
        lines.append(bytes(line))

    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)

    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(b"".join(lines), 9)) + chunk(b"IEND", b""))


def outputs():
    return {"icons.svg": sprite(), "icon-192.png": png(192, 9), "icon-512.png": png(512, 24),
            "apple-touch-icon.png": png(180, 9)}


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for name, data in outputs().items():
        path = os.path.join(WEB, name)
        try:
            with open(path, "rb") as f:
                same = f.read() == data
        except OSError:
            same = False
        if not same:
            stale.append(name)
            if not check:
                with open(path, "wb") as f:
                    f.write(data)
    if check and stale:
        print("web-icons: out of date (run tools/web-icons.py): " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
